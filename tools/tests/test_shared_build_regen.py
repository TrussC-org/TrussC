"""Offline shared-build regeneration regression (#885), without the full core."""
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]


@unittest.skipUnless(shutil.which('cmake') and shutil.which('make'),
                     'requires CMake and Make')
class SharedBuildRegenTests(unittest.TestCase):
    def setUp(self):
        self.scratch = tempfile.TemporaryDirectory(dir=ROOT)
        self.addCleanup(self.scratch.cleanup)
        self.root = Path(self.scratch.name)
        self.core = self.root / 'core'
        platform = 'macos' if sys.platform == 'darwin' else (
            'windows' if sys.platform == 'win32' else 'linux')
        self.shared = self.core / f'build-{platform}'
        shutil.copytree(ROOT / 'core/cmake', self.core / 'cmake')
        shutil.copytree(ROOT / 'core/resources', self.core / 'resources')
        (self.core / 'include').mkdir()
        (self.core / 'tools').mkdir()
        (self.core / 'tools/template.h').write_text('#define FIXTURE_VALUE 42\n', encoding="utf-8")
        (self.core / 'core.cpp').write_text(
            '#include "generated.h"\nint fixture() { return FIXTURE_VALUE; }\n', encoding="utf-8")
        # A source-tree output with a tool dependency reproduces shader rules
        # whose relative paths belong to the last app that configured the core.
        (self.core / 'CMakeLists.txt').write_text('''
cmake_minimum_required(VERSION 3.20)
project(TrussC LANGUAGES C CXX)
add_custom_command(OUTPUT "${CMAKE_CURRENT_SOURCE_DIR}/include/generated.h"
    COMMAND "${CMAKE_COMMAND}" -E copy_if_different
        "${CMAKE_CURRENT_SOURCE_DIR}/tools/template.h"
        "${CMAKE_CURRENT_SOURCE_DIR}/include/generated.h"
    DEPENDS "${CMAKE_CURRENT_SOURCE_DIR}/tools/template.h" VERBATIM)
add_custom_target(TrussC_shaders_gen
    DEPENDS "${CMAKE_CURRENT_SOURCE_DIR}/include/generated.h")
add_library(TrussC_shaders INTERFACE)
add_dependencies(TrussC_shaders TrussC_shaders_gen)
target_include_directories(TrussC_shaders INTERFACE "${CMAKE_CURRENT_SOURCE_DIR}/include")
add_library(TrussC STATIC core.cpp)
add_library(tc::TrussC ALIAS TrussC)
target_link_libraries(TrussC PUBLIC TrussC_shaders)
include("${CMAKE_CURRENT_SOURCE_DIR}/cmake/use_addon.cmake")
function(trussc_setup_icon target)
endfunction()
function(trussc_setup_manifest target)
endfunction()
''', encoding="utf-8")
        self.apps = [self.root / 'addons/addon/nested/first', self.core / 'tests/second']
        self.third_app = self.root / 'throwaway/third'
        for app in [*self.apps, self.third_app]:
            (app / 'src').mkdir(parents=True)
            (app / 'src/main.cpp').write_text(
                '#include "generated.h"\nint fixture();\n'
                'int main() { return fixture() == FIXTURE_VALUE ? 0 : 1; }\n', encoding="utf-8")
            (app / 'CMakeLists.txt').write_text(f'''
cmake_minimum_required(VERSION 3.20)
project({app.name} LANGUAGES C CXX)
set(TRUSSC_DIR "{self.core.as_posix()}")
include("${{TRUSSC_DIR}}/cmake/trussc_app.cmake")
trussc_app()
file(APPEND "${{CMAKE_BINARY_DIR}}/configure-calls" "configure\\n")
''', encoding="utf-8")

    def command(self, *args):
        result = subprocess.run(list(map(str, args)), capture_output=True, text=True, timeout=30, encoding="utf-8")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def configure(self, app, generator):
        self.command('cmake', '-S', app, '-B', app / 'build', '-G', generator,
                     '-DTC_HOT_RELOAD=OFF')

    def build(self, app):
        self.command('cmake', '--build', app / 'build')
        executable = app / 'bin' / app.name
        if sys.platform == 'darwin':
            executable = app / 'bin' / f'{app.name}.app' / 'Contents/MacOS' / app.name
        self.command(executable)

    def retry_build(self, app, target=None, expect_failure=False):
        args = ['cmake', '--build', str(app / 'build')]
        if target:
            args += ['--target', target]
        result = subprocess.run(args, capture_output=True, text=True, timeout=30, encoding="utf-8")
        output = result.stdout + result.stderr
        self.assertNotIn('No rule to make target', output)
        self.assertNotIn('No such file or directory', output)
        self.assertNotIn('cd:', output)
        if expect_failure:
            self.assertNotEqual(result.returncode, 0, output)
        if result.returncode:
            diagnostic = (f'TrussC: core/{self.shared.name} was regenerated by another app; '
                          'build again to reconfigure (#885)')
            self.assertIn(diagnostic, [line.strip() for line in output.splitlines()])
            self.assertEqual(output.count(f'TrussC: core/{self.shared.name}'), 1, output)
            self.command(*args)
        return result.returncode

    def configure_count(self, app):
        return (app / 'build/configure-calls').read_text(encoding="utf-8").count('configure\n')

    def test_make_switches_regenerate_without_recompiling_core(self):
        self.check_serial_switches(self.apps)

    def test_make_switches_regenerate_in_reverse_depth_order(self):
        self.check_serial_switches(self.apps[::-1])

    def test_deleted_last_owner_build_directory_regenerates(self):
        first, second = self.apps
        for app in self.apps:
            self.configure(app, 'Unix Makefiles')
            self.build(app)
        self.configure(self.third_app, 'Unix Makefiles')
        stamp = self.shared / '.tc_configure_owner'
        deleted_build = self.third_app / 'build'
        self.assertEqual(stamp.read_text(encoding="utf-8"), str(deleted_build))
        shutil.rmtree(deleted_build)
        self.assertFalse(deleted_build.exists())

        # B may recover immediately or emit the ownership hint once, then
        # recover. A must then switch back without another failed build.
        for app in (second, first):
            count = self.configure_count(app)
            result = self.retry_build(app)
            if app == first:
                self.assertEqual(result, 0, 'A failed after B recovered')
            self.assertEqual(self.configure_count(app), count + 1)
            self.assertEqual(stamp.read_text(encoding="utf-8"), str(app / 'build'))
            self.build(app)
            self.assertEqual(self.configure_count(app), count + 1)
        self.assertFalse(deleted_build.exists())

    def check_serial_switches(self, apps):
        first, second = apps
        shared = self.shared
        stamp = shared / '.tc_configure_owner'
        self.configure(first, 'Unix Makefiles')
        self.build(first)
        self.configure(second, 'Unix Makefiles')
        self.build(second)
        core_object = shared / 'CMakeFiles/TrussC.dir/core.cpp.o'
        before = core_object.stat().st_mtime_ns
        for app in (first, second):
            count = self.configure_count(app)
            self.build(app)
            self.assertEqual(self.configure_count(app), count + 1)
            self.assertEqual(stamp.read_text(encoding="utf-8"), str(app / 'build'))
            self.assertEqual(core_object.stat().st_mtime_ns, before)
            same_count = self.configure_count(app)
            same_mtime = stamp.stat().st_mtime_ns
            self.build(app)
            self.assertEqual(self.configure_count(app), same_count)
            self.assertEqual(stamp.stat().st_mtime_ns, same_mtime)

        count = self.configure_count(second)
        previous_mtime = stamp.stat().st_mtime_ns
        self.build(second)
        self.assertEqual(self.configure_count(second), count)
        self.assertEqual(stamp.stat().st_mtime_ns, previous_mtime)

    def test_same_app_configure_does_not_rewrite_stamp(self):
        app = self.apps[0]
        self.configure(app, 'Unix Makefiles')
        stamp = self.shared / '.tc_configure_owner'
        self.assertEqual(stamp.read_text(encoding="utf-8"), str(app / 'build'))
        # A known timestamp detects rewrites without relying on sleep duration
        # or the filesystem clock having advanced between configure calls.
        os.utime(stamp, ns=(1600000000000000000, 1600000000000000000))
        previous_mtime = stamp.stat().st_mtime_ns
        self.configure(app, 'Unix Makefiles')
        self.assertEqual(stamp.stat().st_mtime_ns, previous_mtime)
        self.build(app)
        self.assertEqual(self.configure_count(app), 2)

    def test_equal_timestamp_owner_change_fails_safely_then_regenerates(self):
        first, second = self.apps
        shared = self.shared
        stamp = shared / '.tc_configure_owner'
        self.configure(first, 'Unix Makefiles')
        self.build(first)
        core_object = shared / 'CMakeFiles/TrussC.dir/core.cpp.o'
        before = core_object.stat().st_mtime_ns
        # Check direct core and shader builds as well as the default app graph.
        for target in (None, 'TrussC', 'TrussC_shaders_gen'):
            with self.subTest(target=target):
                self.configure(second, 'Unix Makefiles')
                self.build(second)
                epoch = stamp.stat().st_mtime_ns
                outputs = (first / 'build/Makefile',
                           first / 'build/CMakeFiles/cmake.check_cache')
                for path in (stamp, *outputs):
                    os.utime(path, ns=(epoch, epoch))
                count = self.configure_count(first)
                # retry_build requires the one diagnostic, then a successful retry.
                self.retry_build(first, target, expect_failure=True)
                self.assertEqual(self.configure_count(first), count + 1)
                self.assertEqual(stamp.read_text(encoding="utf-8"), str(first / 'build'))
                self.build(first)
                self.assertEqual(self.configure_count(first), count + 1)
                self.assertEqual(core_object.stat().st_mtime_ns, before)

    def test_content_mismatch_with_older_stamp_primes_next_reconfigure(self):
        app = self.apps[0]
        self.configure(app, 'Unix Makefiles')
        self.build(app)
        stamp = self.shared / '.tc_configure_owner'
        stamp.write_text(str(self.apps[1] / 'build'), encoding="utf-8")
        os.utime(stamp, ns=(1600000000000000000, 1600000000000000000))
        count = self.configure_count(app)
        result = subprocess.run(['cmake', '--build', str(app / 'build')],
                                capture_output=True, text=True, timeout=30, encoding="utf-8")
        self.assertNotEqual(result.returncode, 0)
        self.assertNotIn('No rule to make target', result.stdout + result.stderr)
        self.assertIn('build again to reconfigure (#885)',
                      ' '.join((result.stdout + result.stderr).split()))
        self.assertEqual(self.configure_count(app), count)
        for output in ('Makefile', 'CMakeFiles/cmake.check_cache'):
            self.assertGreater(stamp.stat().st_mtime_ns,
                               (app / 'build' / output).stat().st_mtime_ns)
        self.build(app)
        self.assertEqual(self.configure_count(app), count + 1)
        self.build(app)
        self.assertEqual(self.configure_count(app), count + 1)

    def test_same_app_build_rerun_rebuild_cache_and_guest(self):
        app = self.apps[0]
        self.configure(app, 'Unix Makefiles')
        self.build(app)
        cmakelists = app / 'CMakeLists.txt'
        cmakelists.write_text(cmakelists.read_text(encoding="utf-8") + '\n# Trigger make reconfigure\n', encoding="utf-8")
        # Exercise cmake --build -> make -> cmake --check-build-system.
        self.build(app)
        self.assertEqual(self.configure_count(app), 2)
        self.command('make', '-C', app / 'build', 'rebuild_cache')
        self.assertEqual(self.configure_count(app), 3)
        self.build(app)
        self.assertEqual(self.configure_count(app), 3)

        (self.core / 'include/TrussC.h').write_text('#pragma once\n', encoding="utf-8")
        for other in self.apps:
            (other / 'src/guest.cpp').write_text(
                '#define TC_HOT_RELOAD\nint guest_fixture() { return 42; }\n', encoding="utf-8")
            self.configure(other, 'Unix Makefiles')
            self.build(other)
        for other in self.apps:
            count = self.configure_count(other)
            self.command('cmake', '--build', other / 'build', '--target', 'guest')
            self.assertEqual(self.configure_count(other), count + 1)
            cmakelists = other / 'CMakeLists.txt'
            cmakelists.write_text(cmakelists.read_text(encoding="utf-8") + '\n# Guest reconfigure\n', encoding="utf-8")
            self.command('cmake', '--build', other / 'build', '--target', 'guest')
            self.assertEqual(self.configure_count(other), count + 2)
            self.command('cmake', '--build', other / 'build', '--target', 'guest')
            self.assertEqual(self.configure_count(other), count + 2)

    def test_oversized_owner_is_replaced_during_configure_and_build(self):
        app = self.apps[0]
        self.configure(app, 'Unix Makefiles')
        self.build(app)
        stamp = self.shared / '.tc_configure_owner'
        # A valid prefix plus excess bytes must not pass an owner comparison.
        oversized = str(app / 'build') + 'x' * 8192
        stamp.write_text(oversized, encoding="utf-8")
        self.configure(app, 'Unix Makefiles')
        self.assertEqual(stamp.read_text(encoding="utf-8"), str(app / 'build'))
        stamp.write_text(oversized, encoding="utf-8")
        epoch = (app / 'build/Makefile').stat().st_mtime_ns
        for path in (stamp, app / 'build/CMakeFiles/cmake.check_cache'):
            os.utime(path, ns=(epoch, epoch))
        self.retry_build(app, expect_failure=True)
        self.assertEqual(stamp.read_text(encoding="utf-8"), str(app / 'build'))
        self.build(app)

    @unittest.skipUnless(shutil.which('ninja'), 'requires Ninja')
    def test_ninja_keeps_per_app_core_without_owner_stamp(self):
        for app in self.apps:
            self.configure(app, 'Ninja')
            self.build(app)
            self.assertTrue((app / 'build/trussc').is_dir())
            self.assertFalse((app / 'build/trussc/.tc_configure_owner').exists())
        for app in self.apps:
            self.build(app)
            self.assertEqual(self.configure_count(app), 1)
        self.assertFalse(self.shared.exists())


if __name__ == '__main__':
    unittest.main()
